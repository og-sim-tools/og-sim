"""Turn the Combat Training CSVs (ranks + levels) into data/training.yaml and check them.

Usage: python -I tools/training-csv/convert.py <combat-training-ranks.csv> <combat-training-levels.csv> data/training.yaml
"""
import csv, sys

ranks_csv, levels_csv, out = sys.argv[1:4]
ranks = list(csv.DictReader(open(ranks_csv, encoding='utf-8')))
levels = list(csv.DictReader(open(levels_csv, encoding='utf-8')))

problems = []
for i, r in enumerate(ranks):
    if int(r['rank_level']) != i: problems.append(f'rank row {i}: rank_level {r["rank_level"]}')
    if int(r['observed_equal_three_track_tier']) != 10 * i: problems.append(f'rank {i}: three-track tier {r["observed_equal_three_track_tier"]}')
    if int(r['observed_training_road_progress']) != 30 * i: problems.append(f'rank {i}: road progress {r["observed_training_road_progress"]}')
    if i:
        p = ranks[i - 1]
        for a, d in (('MaxHp', 'delta_MaxHp'), ('Attack', 'delta_Attack'), ('Defence', 'delta_Defence')):
            if int(r[a]) - int(p[a]) != int(r[d]): problems.append(f'rank {i}: {a} delta mismatch')
for i, l in enumerate(levels):
    if int(l['tier']) != i: problems.append(f'level row {i}: tier {l["tier"]}')
    if i:
        p = levels[i - 1]
        for a, d in (('MaxHp', 'delta_MaxHp'), ('Attack', 'delta_Attack'), ('Defence', 'delta_Defence')):
            if int(l[a]) - int(p[a]) != int(l[d]): problems.append(f'tier {i}: {a} delta mismatch')

# Rank types in order, with how many numbers each has.
types = []
for r in ranks:
    if not types or types[-1][0] != r['type']: types.append([r['type'], 0])
    types[-1][1] += 1
    if int(r['subtype']) != types[-1][1]: problems.append(f'rank {r["rank_level"]}: subtype {r["subtype"]} out of order')

arr = lambda rows, col: '[' + ', '.join(r[col] for r in rows) + ']'
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write(f'''# Combat Training (Profile tab, "Calculated" stats). GENERATED by tools/training-csv/convert.py from the
# user's combat-training-ranks.csv and combat-training-levels.csv (2026-11-06); don't hand-edit the tables.
#
# How training works (user, 2026-11-06): gold buys up to 10 upgrades each of HP, ATK and Block per rank; once all
# three are at 10 the next rank is reached (e.g. Champion 12 → Champion 13).
# Reading of the tables (flagged, not confirmed by an in-game number yet):
#   - each stat has its own track; its tier = 10 × rank level + that stat's upgrades in the current rank (0–10);
#   - a stat's training value = rank_bonus[rank level] + track[tier] (MaxHp → HP, Attack → ATK, Defence → Block).
source: observed
verified: true
upgrades_per_rank: 10
# Rank types in order, as named in the CSV ("type"), with how many numbers each has. `name` is what the Profile tab
# shows: the in-game names aren't known yet (the user wrote "Champion", which isn't in the CSV).
ranks:
''')
    for t, n in types:
        f.write(f'  - {{ id: {t.lower()}, name: {t}, numbers: {n} }}\n')
    f.write(f'''# Bonus for the rank reached, by rank level 0–{len(ranks) - 1} (Apprentice 1 = 0).
rank_bonus:
  hp: {arr(ranks, 'MaxHp')}
  atk: {arr(ranks, 'Attack')}
  block: {arr(ranks, 'Defence')}
# Each stat's track, by tier 0–{len(levels) - 1}.
track:
  hp: {arr(levels, 'MaxHp')}
  atk: {arr(levels, 'Attack')}
  block: {arr(levels, 'Defence')}
''')
print('ranks', len(ranks), 'tiers', len(levels), 'types', types)
print('problems:', problems or 'none')
