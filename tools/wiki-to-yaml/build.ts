/** Build the wiki YAML files in memory from the docs/wiki-data markdown (pure; no file writes). */
import { stringify } from 'yaml';
import { type Flag, parseBlessings, parseGear, parseHeroes, parseItems, parsePets, parseStatuses } from './parse';

export interface GeneratedFile {
  /** Relative to data/, e.g. "items/wiki/warrior.yaml". */
  path: string;
  category: string;
  content: string;
  count: number;
}

export interface BuildResult {
  files: GeneratedFile[];
  flags: Flag[];
  blessingSlotsByLevel: Record<string, number>;
}

/** `read(name)` returns the text of docs/wiki-data/<name>. */
export function buildWikiYaml(read: (name: string) => string): BuildResult {
  const files: GeneratedFile[] = [];
  const flags: Flag[] = [];
  const add = (category: string, file: string, from: string, entries: unknown[]) => {
    const header =
      `# GENERATED by tools/wiki-to-yaml from docs/wiki-data/${from} — don't hand-edit.\n` +
      `# Put corrections in data/${category}/manual/ (same id overrides field by field).\n`;
    files.push({
      path: `${category}/wiki/${file}.yaml`,
      category,
      content: header + stringify(entries, { lineWidth: 0, aliasDuplicateObjects: false }),
      count: entries.length,
    });
  };

  const items = parseItems(read('items.md'));
  for (const [file, entries] of Object.entries(items.files)) add('items', file, 'items.md', entries);
  flags.push(...items.flags);

  const gear = parseGear(read('gear.md'));
  // Gear sharing an id with an item gets a `_gear` suffix, so one id names one thing.
  const itemIds = new Set(Object.values(items.files).flat().map((e) => e.id as string));
  for (const g of gear.gear) {
    if (itemIds.has(g.id as string)) {
      flags.push({ file: 'gear.md', entry: g.name as string, message: `same id as an item ("${g.id}"); gear id is "${g.id}_gear"` });
      g.id = `${g.id}_gear`;
    }
  }
  add('gear', 'gear', 'gear.md', gear.gear);
  add('auras', 'auras', 'gear.md', gear.auras);
  flags.push(...gear.flags);

  const heroes = parseHeroes(read('heroes.md'));
  for (const [file, entries] of Object.entries(heroes.files)) add('heroes', file, 'heroes.md', entries);
  flags.push(...heroes.flags);

  const heroSkills = new Map<string, string[]>();
  for (const list of Object.values(heroes.files)) {
    for (const h of list) heroSkills.set(h.id as string, (h.skills as { id: string }[]).map((s) => s.id));
  }
  const blessings = parseBlessings(read('blessings.md'), heroSkills);
  for (const [file, entries] of Object.entries(blessings.files)) add('blessings', file, 'blessings.md', entries);
  flags.push(...blessings.flags);

  const pets = parsePets(read('pets.md'));
  add('pets', 'pets', 'pets.md', pets.pets);
  flags.push(...pets.flags);

  const statuses = parseStatuses(read('statuses.md'));
  add('statuses', 'statuses', 'statuses.md', statuses.statuses);
  add('enemy_traits', 'enemy_traits', 'statuses.md', statuses.traits);
  flags.push(...statuses.flags);

  return { files, flags, blessingSlotsByLevel: blessings.slotsByLevel };
}
